const DIGITS = "۰۱۲۳۴۵۶۷۸۹";
/** Latin → Persian digits (also turns "." into the Persian decimal separator "٫"). */
export const faNum = (value: string) => value.replace(/\d/g, (d) => DIGITS[Number(d)]).replace(/(\d|[۰-۹])\.(?=[۰-۹])/g, "$1٫");

/** "25 more hours" → "۲۵", "80% faster" → "۸۰٪", "2.8x faster" → "۲٫۸ برابر" */
function figure(value: string) {
  const match = value.match(/^([\d.]+)(%|x)?/);
  if (!match) return value;
  const [, number, unit] = match;
  const n = faNum(number);
  return unit === "%" ? `${n}٪` : unit === "x" ? `${n} برابر` : n;
}

