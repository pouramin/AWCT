"""Preserve distinct source paths when Apple reuses a basename."""
from pathlib import Path
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
from bs4 import BeautifulSoup
import json, urllib.request

root = Path(__file__).resolve().parents[1]
output = root / 'apps/apple/public/sites/apple'
manifest_path = root / 'docs/research/apple/asset-map.json'
manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
groups = defaultdict(list)
for url, local in manifest['assets'].items(): groups[local].append(url)
collisions = {local: urls for local, urls in groups.items() if len(urls) > 1}
replacements = {
    url: '/sites/apple/' + url.split('/images/', 1)[-1].replace('/', '--')
    for urls in collisions.values() for url in urls
}
def download(pair):
    url, local = pair
    with urllib.request.urlopen(url, timeout=30) as response:
        if 'image/' not in response.headers.get('Content-Type', ''): raise ValueError(url)
        (output / local.rsplit('/', 1)[-1]).write_bytes(response.read())
with ThreadPoolExecutor(max_workers=8) as pool: list(pool.map(download, replacements.items()))
source_path = root / 'apps/apple/src/components/sites/apple/source.json'
data = json.loads(source_path.read_text(encoding='utf-8'))
soup = BeautifulSoup((root / 'temp/apple/source.html').read_text(encoding='utf-8'), 'html.parser')
for index, section in enumerate(soup.select('main section')):
    originals = {}
    for picture in section.select('picture'):
        image = picture.find('img')
        if not image or not image.get('src', '').startswith('/'): continue
        small = picture.find('source', media='(max-width:734px)')
        originals[picture.get('class', [''])[0]] = {
            'src': 'https://www.apple.com' + image['src'],
            'small': 'https://www.apple.com' + small['srcset'].split(',')[0].split(' ')[0] if small else 'https://www.apple.com' + image['src']
        }
    pictures = data[index]['pictures'] + [card['picture'] for card in data[index]['cards'] if card['picture']]
    for picture in pictures:
        original = originals.get(picture['key'])
        if original:
            for size in ['src', 'small']:
                if original[size] in replacements: picture[size] = replacements[original[size]]
source_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
manifest['assets'].update(replacements)
manifest['basenameCollisionsResolved'] = collisions
manifest_path.write_text(json.dumps(manifest, indent=2), encoding='utf-8')
# Only remove obsolete files generated by this task, after checking the exact parent.
for local in collisions:
    target = (output / local.rsplit('/', 1)[-1]).resolve()
    if target.parent != output.resolve(): raise ValueError('Unexpected asset target')
    if target.exists(): target.unlink()
print({'collisionGroups': len(collisions), 'distinctImagesRecovered': len(replacements)})
